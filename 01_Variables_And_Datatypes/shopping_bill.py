# 55. Shopping Bill

# Take input:

# Product price
# Quantity
# Discount percentage

# Calculate the final bill.
product_price= 700
quantity = 3
discount_percentage= 4
product_amount= product_price * quantity
discount_amount= product_price * quantity * discount_percentage / 100
final_amount= product_amount - discount_amount
print("Final amount to be paid is",final_amount)
